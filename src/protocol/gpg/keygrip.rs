    #[test]
    fn rejects_mismatched_and_malformed_keys() {
        let rsa_attrs = AlgorithmAttributes::Rsa(RsaAttributes {
            n_bits: 2048,
            e_bits: 32,
            format: RsaImportFormat::Standard,
        });
        let ed_attrs = AlgorithmAttributes::Ecc {
            kind: EccKind::EdDsa,
            curve: Curve::Ed25519,
            import_with_public_key: false,
        };
        let p256_attrs = AlgorithmAttributes::Ecc {
            kind: EccKind::Ecdsa,
            curve: Curve::NistP256,
            import_with_public_key: false,
        };

        // Mismatched attributes vs public key variant
        assert!(compute_keygrip(rsa_attrs, &PublicKey::Ecc { point: vec![0; 32] }).is_err());
        assert!(
            compute_keygrip(
                ed_attrs,
                &PublicKey::Rsa {
                    modulus: vec![0x81],
                    exponent: vec![0x01, 0x00, 0x01],
                }
            )
            .is_err()
        );

        // Empty / all-zero RSA modulus
        assert!(
            compute_keygrip(
                rsa_attrs,
                &PublicKey::Rsa {
                    modulus: vec![0x00; 16],
                    exponent: vec![0x01, 0x00, 0x01],
                }
            )
            .is_err()
        );

        // Bad Ed25519 point length / wrong prefix
        assert!(compute_keygrip(ed_attrs, &PublicKey::Ecc { point: vec![0; 31] }).is_err());
        assert!(compute_keygrip(ed_attrs, &PublicKey::Ecc { point: vec![0x04; 33] }).is_err());

        // Bad NIST P-256 point length / missing 0x04 prefix
        assert!(compute_keygrip(p256_attrs, &PublicKey::Ecc { point: vec![0x04; 64] }).is_err());
        assert!(compute_keygrip(p256_attrs, &PublicKey::Ecc { point: vec![0x02; 65] }).is_err());
    }
