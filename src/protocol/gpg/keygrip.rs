    fn hex_to_bytes(hex: &str) -> Vec<u8> {
        assert_eq!(hex.len() % 2, 0);
        hex.as_bytes()
            .as_chunks::<2>()
            .0
            .iter()
            .map(|pair| {
                let s = std::str::from_utf8(pair).unwrap();
                u8::from_str_radix(s, 16).unwrap()
            })
            .collect()
    }

    #[test]
    fn keygrip_display_and_from_str_roundtrip() {
        let hex = "4D896546DD116147366CE517F2B3EA6583CA85B6";
        let kg: Keygrip = hex.parse().unwrap();
        assert_eq!(kg.to_string(), hex);
        assert_eq!(kg.as_bytes().len(), 20);
        assert_eq!(kg.as_bytes()[0], 0x4D);
        assert_eq!(kg.as_bytes()[19], 0xB6);

        // Case-insensitive parsing
        let lower: Keygrip = hex.to_lowercase().parse().unwrap();
        assert_eq!(lower, kg);

        // Invalid lengths and non-hex characters
        assert!("".parse::<Keygrip>().is_err());
        assert!("4D8965".parse::<Keygrip>().is_err());
        assert!(format!("{hex}00").parse::<Keygrip>().is_err());
        assert!("GGGGGGGGGGGGGGGGGGGGGGGGGGGGGGGGGGGGGGGG"
            .parse::<Keygrip>()
            .is_err());
    }

