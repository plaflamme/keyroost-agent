use std::fmt;
use std::str::FromStr;

use keyroost_openpgp::{AlgorithmAttributes, Curve, PublicKey};
use sha1::{Digest, Sha1};

/// A 20-byte libgcrypt keygrip (SHA-1 digest of canonical public-key parameters).
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub(crate) struct Keygrip([u8; 20]);

impl Keygrip {
    /// Returns the raw 20-byte keygrip digest.
    #[must_use]
    pub(crate) const fn as_bytes(&self) -> &[u8; 20] {
        &self.0
    }
}

impl fmt::Display for Keygrip {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        for byte in &self.0 {
            write!(f, "{byte:02X}")?;
        }
        Ok(())
    }
}

impl FromStr for Keygrip {
    type Err = crate::Error;

    fn from_str(s: &str) -> Result<Self, Self::Err> {
        let bytes = s.as_bytes();
        if bytes.len() != 40 {
            return Err(crate::Error::Other(
                format!("invalid keygrip length: expected 40 hex chars, got {}", s.len()).into(),
            ));
        }

        let mut out = [0u8; 20];
        let (pairs, _) = bytes.as_chunks::<2>();
        for (slot, pair) in out.iter_mut().zip(pairs) {
            let hi = decode_hex_nibble(pair[0])?;
            let lo = decode_hex_nibble(pair[1])?;
            *slot = (hi << 4) | lo;
        }
        Ok(Self(out))
    }
}

fn decode_hex_nibble(b: u8) -> Result<u8, crate::Error> {
    match b {
        b'0'..=b'9' => Ok(b - b'0'),
        b'a'..=b'f' => Ok(b - b'a' + 10),
        b'A'..=b'F' => Ok(b - b'A' + 10),
        _ => Err(crate::Error::Other(
            format!("invalid hex character in keygrip: 0x{b:02x}").into(),
        )),
    }
}

/// Computes the libgcrypt keygrip (`gcry_pk_get_keygrip`) for an `OpenPGP` public key.
///
/// - **RSA** (`cipher/rsa.c:rsa_get_keygrip`): SHA-1 over the modulus `n` encoded as
///   `GCRYMPI_FMT_STD` (leading zeros stripped, with a single `0x00` prefix byte if the
///   most-significant bit is set).
/// - **ECC** (`cipher/ecc.c:ecc_get_keygrip`): SHA-1 over the canonical S-expression
///   `(1:p<len>:<p>)(1:a<len>:<a>)(1:b<len>:<b>)(1:g<len>:<g>)(1:n<len>:<n>)(1:q<len>:<q>)`
///   where `p`, `a`, `b`, and `n` are libgcrypt's unsigned MPI curve parameters
///   (`GCRYMPI_FMT_USG`, leading zeros stripped), `g` is the uncompressed generator
///   `04 || gx || gy`, and `q` is the public point (`04 || x || y` for Weierstrass curves,
///   or the 32-byte compressed/u-coordinate point without the `OpenPGP` `0x40` prefix for
///   Ed25519 and X25519/Cv25519).
pub(crate) fn compute_keygrip(
    attrs: AlgorithmAttributes,
    pubkey: &PublicKey,
) -> Result<Keygrip, crate::Error> {
    match (attrs, pubkey) {
        (AlgorithmAttributes::Rsa(_), PublicKey::Rsa { modulus, .. }) => rsa_keygrip(modulus),
        (AlgorithmAttributes::Ecc { curve, .. }, PublicKey::Ecc { point }) => {
            ecc_keygrip(curve, point)
        }
        (AlgorithmAttributes::Rsa(_), PublicKey::Ecc { .. }) => Err(crate::Error::Other(
            "algorithm attributes specify RSA but public key is ECC".into(),
        )),
        (AlgorithmAttributes::Ecc { .. }, PublicKey::Rsa { .. }) => Err(crate::Error::Other(
            "algorithm attributes specify ECC but public key is RSA".into(),
        )),
    }
}

fn rsa_keygrip(modulus: &[u8]) -> Result<Keygrip, crate::Error> {
    let stripped = strip_leading_zeros(modulus);
    if stripped.is_empty() {
        return Err(crate::Error::Other(
            "RSA public key modulus is empty or zero".into(),
        ));
    }

    let mut hasher = Sha1::new();
    // GCRYMPI_FMT_STD: two's-complement positive integer, prepend 0x00 when MSB is set.
    if stripped[0] & 0x80 != 0 {
        hasher.update([0x00]);
    }
    hasher.update(stripped);
    Ok(Keygrip(hasher.finalize().into()))
}

fn ecc_keygrip(curve: Curve, point: &[u8]) -> Result<Keygrip, crate::Error> {
    let q = normalize_ecc_point(curve, point)?;
    let params = curve_params(curve);

    let mut hasher = Sha1::new();
    hash_sexp_param(&mut hasher, b"p", params.p);
    hash_sexp_param(&mut hasher, b"a", params.a);
    hash_sexp_param(&mut hasher, b"b", params.b);
    hash_sexp_param(&mut hasher, b"g", params.g);
    hash_sexp_param(&mut hasher, b"n", params.n);
    hash_sexp_param(&mut hasher, b"q", q);
    Ok(Keygrip(hasher.finalize().into()))
}

fn normalize_ecc_point(curve: Curve, point: &[u8]) -> Result<&[u8], crate::Error> {
    if curve.is_25519() {
        // Cards surface raw 32-byte points; OpenPGP wire packets prepend 0x40.
        // libgcrypt hashes the raw 32-byte point without the 0x40 prefix.
        return match point {
            [0x40, rest @ ..] if rest.len() == 32 => Ok(rest),
            _ if point.len() == 32 => Ok(point),
            _ => Err(crate::Error::Other(
                format!(
                    "invalid {} public point length: expected 32 bytes (or 33 with 0x40 prefix), got {}",
                    curve.label(),
                    point.len()
                )
                .into(),
            )),
        };
    }

    let expected_len = 1 + 2 * curve.field_len();
    if point.len() != expected_len || point.first() != Some(&0x04) {
        return Err(crate::Error::Other(
            format!(
                "invalid {} public point: expected {expected_len}-byte uncompressed point (0x04 prefix), got {} bytes",
                curve.label(),
                point.len()
            )
            .into(),
        ));
    }
    Ok(point)
}

fn strip_leading_zeros(bytes: &[u8]) -> &[u8] {
    let first_non_zero = bytes.iter().position(|&b| b != 0).unwrap_or(bytes.len());
    &bytes[first_non_zero..]
}

fn hash_sexp_param(hasher: &mut Sha1, name: &[u8], value: &[u8]) {
    // Canonical S-expression list element: `(<name_len>:<name><val_len>:<val>)`.
    let header = format!("({}:", name.len());
    let val_len = format!("{}:", value.len());
    hasher.update(header.as_bytes());
    hasher.update(name);
    hasher.update(val_len.as_bytes());
    hasher.update(value);
    hasher.update(b")");
}

/// Curve parameters as stored in libgcrypt `cipher/ecc-curves.c`.
///
/// `p`, `a`, `b`, and `n` are unsigned big-endian integers with leading zeros stripped
/// (`GCRYMPI_FMT_USG`; zero is `&[]`). `g` is the uncompressed base point `04 || gx || gy`.
struct CurveParams {
    p: &'static [u8],
    a: &'static [u8],
    b: &'static [u8],
    g: &'static [u8],
    n: &'static [u8],
}

const fn curve_params(curve: Curve) -> &'static CurveParams {
    match curve {
        Curve::Ed25519 => &ED25519_PARAMS,
        Curve::X25519 => &CURVE25519_PARAMS,
        Curve::NistP256 => &NIST_P256_PARAMS,
        Curve::NistP384 => &NIST_P384_PARAMS,
        Curve::NistP521 => &NIST_P521_PARAMS,
        Curve::Secp256k1 => &SECP256K1_PARAMS,
        Curve::BrainpoolP256r1 => &BRAINPOOL_P256R1_PARAMS,
        Curve::BrainpoolP384r1 => &BRAINPOOL_P384R1_PARAMS,
        Curve::BrainpoolP512r1 => &BRAINPOOL_P512R1_PARAMS,
    }
}

